err_type err_code;
uint32_t total_error_count = 0;

static void handle_err_code(const err_type err_code, const char *function_name, uint32_t &total_error_count)
{
    if (err_code != ERR_OK)
    {
        fprintf(stderr, "Error in function %s with code %d\n", function_name, err_code);
        total_error_count += 1;
    }
}

static void handle_crypto_result(const uint8_t *result_array, const uint8_t *expected_array, const size_t arr_size,
                                 const char *function_name, uint32_t &total_error_count)
{
    if (memcmp(result_array, expected_array, arr_size) != 0)
    {
        fprintf(stderr, "Error in function %s implementation found\n", function_name);
        total_error_count += 1;
    }
}

